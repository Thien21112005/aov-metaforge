const I18N_KEY = "aov_lang";
let currentLang = "vi";
try {
  const saved = localStorage.getItem(I18N_KEY);
  if (saved === "vi" || saved === "en") currentLang = saved;
} catch {
  /* Storage unavailable: stay on the default language */
}

function t(key, params) {
  const table = I18N_STRINGS[currentLang];
  let text = key in table ? table[key] : I18N_STRINGS.vi[key] ?? key;
  if (params) {
    Object.keys(params).forEach((name) => {
      text = text.split(`{${name}}`).join(params[name]);
    });
  }
  return text;
}

function applyStaticI18n(root = document) {
  document.documentElement.lang = currentLang;
  document.title = t("doc.title");
  const heroCount = typeof HEROES_DATABASE !== "undefined" ? HEROES_DATABASE.length : 0;
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n, { n: heroCount });
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  root.querySelectorAll("[data-i18n-label]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nLabel));
  });
}

function setLanguage(lang) {
  if (lang === currentLang || !I18N_STRINGS[lang]) return;
  currentLang = lang;
  try {
    localStorage.setItem(I18N_KEY, lang);
  } catch {
    /* Choice lasts for this visit only */
  }
  applyStaticI18n();
  document.dispatchEvent(new CustomEvent("aov:langchange", { detail: { lang } }));
}
